def render_html(card: OutingCard) -> str:
    """Render the outing card as a self-contained HTML file."""
    challenges_html = "".join(f"<li>{c}</li>" for c in card.off_screen_challenges)

    # Format generated_at nicely
    try:
        dt = datetime.fromisoformat(card.generated_at.replace("Z", "+00:00"))
        generated_str = dt.strftime("%B %d, %Y at %I:%M %p")
    except Exception:
        generated_str = card.generated_at

    return HTML_TEMPLATE.format(
        activity=card.activity.label,
        location=card.location_name,
        time_minutes=card.time_available_minutes,
        generated_at=generated_str,
        route_suggestion=card.route_suggestion,
        seasonal_highlights=card.seasonal_highlights,
        challenges_html=challenges_html,
        safety_note=card.safety_note,
        weather_summary=card.weather_summary,
    )


def save_html(card: OutingCard, output_path: Path | str) -> Path:
    """Save the card as an HTML file."""
    path = Path(output_path)
    path.write_text(render_html(card), encoding="utf-8")
    return path


class TrailheadPDF(FPDF):
    """Custom PDF class for Trailhead cards."""

    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.set_auto_page_break(auto=True, margin=20)

    def header(self):
        pass

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, "Generated by Trailhead", align="C")

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(46, 125, 50)  # #2E7D32
        self.cell(0, 6, title.upper(), new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(46, 125, 50)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(3)

    def section_body(self, text: str):
        self.set_font("Helvetica", "", 10)
        self.set_text_color(51, 51, 51)
        self.multi_cell(0, 5, text)
        self.ln(2)

    def challenge_item(self, index: int, text: str):
        self.set_fill_color(241, 248, 233)  # #F1F8E9
        self.set_draw_color(46, 125, 50)
        w = self.w - self.l_margin - self.r_margin
        self.set_font("Helvetica", "", 10)
        self.set_text_color(51, 51, 51)
        # Number
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(46, 125, 50)
        self.cell(8, 5, f"{index}.")
        self.set_font("Helvetica", "", 10)
        self.set_text_color(51, 51, 51)
        self.multi_cell(w - 8, 5, text, fill=True, border="L")
        self.ln(2)


def render_pdf(card: OutingCard, output_path: Path | str) -> Path:
    """Render the outing card as a PDF file using fpdf2."""
    path = Path(output_path)
    pdf = TrailheadPDF()
    pdf.add_page()

    # Header
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(46, 125, 50)
    pdf.cell(0, 6, card.activity.label.upper(), new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(2)

    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(27, 94, 32)  # #1B5E20
    pdf.cell(0, 12, card.location_name, new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(1)

    # Time and generated
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 100, 100)
    try:
        dt = datetime.fromisoformat(card.generated_at.replace("Z", "+00:00"))
        generated_str = dt.strftime("%B %d, %Y at %I:%M %p")
    except Exception:
        generated_str = card.generated_at
    label = f"{card.time_available_minutes} minutes  •  {generated_str}"
    pdf.cell(0, 6, label, new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(6)

    # Sections
    pdf.section_title("Route")
    pdf.section_body(card.route_suggestion)

    pdf.section_title("Seasonal Highlights")
    pdf.section_body(card.seasonal_highlights)

    pdf.section_title("Off-Screen Challenges")
    for i, challenge in enumerate(card.off_screen_challenges, 1):
        pdf.challenge_item(i, challenge)

    pdf.section_title("Safety")
    pdf.set_fill_color(255, 243, 224)  # #FFF3E0
    pdf.set_draw_color(255, 183, 77)   # #FFB74D
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(230, 81, 0)     # #E65100
    w = pdf.w - pdf.l_margin - pdf.r_margin
    pdf.multi_cell(w, 6, card.safety_note, fill=True, border=1)
    pdf.ln(4)

    # Footer with weather
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(46, 125, 50)
    pdf.cell(0, 5, card.weather_summary, new_x="LMARGIN", new_y="NEXT", align="C")

    pdf.output(str(path))
    return path
